class SearchKnowledgeInput(BaseModel):
    """Схема валідації запиту до векторної бази знань ChromaDB."""

    query: str = Field(
        ...,
        min_length=2,
        max_length=300,
        description="Пошуковий запит до бази знань про подорожі Європою.",
    )
    top_k: int = Field(
        default=3,
        ge=1,
        le=5,
        description="Кількість найбільш релевантних документів для повернення (за замовчуванням 3).",
    )


_collection_cache: chromadb.Collection | None = None


def get_knowledge_collection(persist_dir: str | None = None) -> chromadb.Collection:
    """
    Ініціалізує та повертає персистентну колекцію ChromaDB із завантаженими документами.
    При повторному запуску використовує вже збережені embeddings без повторного додавання.
    """
    global _collection_cache
    if _collection_cache is not None and persist_dir is None:
        return _collection_cache

    target_dir = persist_dir or str(CHROMA_DIR)
    client = chromadb.PersistentClient(path=target_dir)
    collection = client.get_or_create_collection(name="travel_knowledge_base")

    # Завантажуємо документи, якщо колекція порожня або кількість змінилася
    existing_ids = set(collection.get()["ids"])
    missing_docs = [doc for doc in TRAVEL_DOCUMENTS if doc["id"] not in existing_ids]

    if missing_docs:
        collection.add(
            ids=[doc["id"] for doc in missing_docs],
            documents=[doc["content"] for doc in missing_docs],
            metadatas=[{"topic": doc["topic"]} for doc in missing_docs],
        )

    if persist_dir is None:
        _collection_cache = collection
    return collection


@tool(args_schema=SearchKnowledgeInput)
def search_knowledge(query: str, top_k: int = 3) -> str:
    """Пошук довідкової інформації у векторній базі знань про подорожі Європою (ChromaDB).

    Використовуйте цей інструмент, коли потрібні факти, правила, рекомендації або довідкові дані:
    - візовий режим ЄС / безвіз / паспортні вимоги;
    - музеї, пам'ятки, графік роботи та ціни квитків (Лувр, Ейфелева вежа, Колізей, Саграда Фамілія);
    - громадський транспорт, проїзні, потяги TGV/Eurail;
    - правила ручної поклажі лоукостерів (Ryanair, Wizz Air);
    - туристичне страхування, Tax Free, сезонність, безпека туристів, орієнтовний бюджет харчування.

    НЕ використовуйте для арифметичних обчислень (є `calculate`), конвертації валют
    (є `convert_currency`), прогнозу погоди (є `get_weather`), пошуку конкретних готелів
    (є `search_hotels`) або бронювання готелів (є `book_hotel`).
    """
    collection = get_knowledge_collection()
    results = collection.query(query_texts=[query], n_results=top_k)

    docs = results.get("documents", [[]])[0]
    ids = results.get("ids", [[]])[0]
    distances = results.get("distances", [[]])[0]

    if not docs:
        return "У базі знань не знайдено релевантних документів."

    formatted_chunks = []
    for idx, (doc_id, text, dist) in enumerate(zip(ids, docs, distances), start=1):
        formatted_chunks.append(f"[{idx}] ({doc_id}, distance={dist:.3f})\n{text}")
    return "\n---\n".join(formatted_chunks)
